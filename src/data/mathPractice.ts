//  应用题专项练习 · 题目数据（北师大三年级上册）
//  ------------------------------------------------------------
//  对齐陈老师的「审题三步法」（2026-11-18）：圈关系词 → 划数字单位 →
//  说求什么。练习流程 = 标记 → 说 → 算 → 得数，共 4 步（用户定）。
//
//  每道题的题干拆成 segments：
//    · k:'rel'  关系词（一共/还剩/比…多/比…少/几倍/每/至少）—— 练「圈」
//    · k:'num'  数字+单位 —— 练「划」（给眼睛一个落点）
//    · 其余 plain —— 不用标记
//  单测钉死：segments 拼接 === 原文、每题至少 1 个 rel + 1 个 num。
//
//  标记步宽松判定（用户定）：漏圈/漏划才算错；多点的词只提醒不扣。
//  交互借鉴 GitHub 同类项目（prashantkul/help-math：每一步正确就给
//  奖励，而非只看最终答案；greamses/Word-Problems 的标注思路收窄成
//  「只圈骨头词」，避免「所有文字都要圈」的繁琐——用户实测踩过）。
//
//  本项目是英语学习工作台，这里**不接入 SRS / store / ModuleId**，
//  错题单独存 localStorage（见 mathWrong.ts），不升 persist 版本号。
// ============================================================

export interface StepChoice {
  label: string
  correct: boolean
}

/** 题干分块：k 缺省为普通文字；'rel'=圈（关系词）、'num'=划（数字+单位） */
export interface StemSegment {
  t: string
  k?: 'rel' | 'num'
}

export interface WordProblem {
  id: string
  /** 完整题干（segments 依次拼接，单测钉死一致） */
  text: string
  segments: StemSegment[]
  /** 第二步：这道题要我找什么？ */
  ask: { prompt: string; options: StepChoice[] }
  /** 第三步：先算什么？ */
  first: { prompt: string; options: StepChoice[] }
  /** 分步算式（用于第三步脚手架 + 解析展示） */
  steps: string[]
  answer: number
  explain: string
}

/** 分块小工具：s=普通文字 r=关系词（圈） n=数字+单位（划） */
const s = (t: string): StemSegment => ({ t })
const r = (t: string): StemSegment => ({ t, k: 'rel' })
const n = (t: string): StemSegment => ({ t, k: 'num' })

/**
 * 构造一道题：askOptions / firstOptions 里各自有且仅有一个 correct。
 * 选项顺序固定（不随机），e2e 可以用 nth 定位，孩子每次看到一致的布局。
 */
const q = (
  id: string,
  segments: StemSegment[],
  askOptions: [string, string, string],
  askCorrect: number,
  firstOptions: [string, string, string],
  firstCorrect: number,
  steps: [string, string],
  answer: number,
  explain: string,
): WordProblem => ({
  id,
  text: segments.map((seg) => seg.t).join(''),
  segments,
  ask: {
    prompt: '这道题要我找什么？',
    options: askOptions.map((label, i) => ({ label, correct: i === askCorrect })),
  },
  first: {
    prompt: '先算什么？',
    options: firstOptions.map((label, i) => ({ label, correct: i === firstCorrect })),
  },
  steps,
  answer,
  explain,
})

