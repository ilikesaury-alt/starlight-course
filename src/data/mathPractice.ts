// ---------- 带种子的伪随机（mulberry32，可复现）----------
function mulberry32(seed: number): () => number {
  let a = seed >>> 0
  return () => {
    a |= 0
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

function shuffle<T>(arr: T[], rnd: () => number): T[] {
  const a = arr.slice()
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

/**
 * 抽一组题（给定 seed 可复现）。
 * - ids 非空：只取这些 id（重练错题），忽略 count/topic 轮转。
 * - 否则按 topic **轮转**抽样：每轮 5 题会来自不同板块，不会一整轮都是乘减题。
 */
export function wordProblemRound(
  count = 5,
  seed: number = Date.now(),
  ids?: string[],
): WordProblem[] {
  if (ids && ids.length) {
    return WORD_PROBLEMS.filter((p) => ids.includes(p.id))
  }
  const rnd = mulberry32(seed)
  const byTopic = new Map<ProblemTopic, WordProblem[]>()
  for (const p of WORD_PROBLEMS) {
    const list = byTopic.get(p.topic) ?? []
    list.push(p)
    byTopic.set(p.topic, list)
  }
  // 板块顺序随机、每个板块内部也洗牌（都受 seed 控制）
  const queues = shuffle([...byTopic.keys()], rnd).map((topic) =>
    shuffle(byTopic.get(topic)!, rnd),
  )
  const out: WordProblem[] = []
  let i = 0
  while (out.length < count && queues.some((qs) => qs.length)) {
    const queue = queues[i % queues.length]
    if (queue.length) out.push(queue.shift()!)
    i++
  }
  return out
}