export interface WordProblem {
  id: string
  topic: ProblemTopic
  /** 完整题干（segments 依次拼接，单测钉死一致） */
  text: string
  segments: StemSegment[]
  /** 第二步：这道题要我找什么？ */
  ask: { prompt: string; options: StepChoice[] }
  /** 第三步：先算什么？ */
  first: { prompt: string; options: StepChoice[] }
  /** 分步算式（第一步当脚手架、答完展示全部） */
  steps: string[]
  answer: number
  explain: string
}

/** 分块小工具：s=普通文字 r=关系词（圈） n=数字+单位（划） */
const s = (t: string): StemSegment => ({ t })
const r = (t: string): StemSegment => ({ t, k: 'rel' })
const n = (t: string): StemSegment => ({ t, k: 'num' })

// —— 选项打散（2026-11-18 用户实测「闭眼选 A」后加）——
// 原来所有题的正确项都写死在 index 0，孩子不用读题也能全对。
// 这里用 **题号 hash 作种子** 做确定性洗牌：每道题的正确项位置不同，
// 但同一道题每次打开位置一致（重练错题时不会因为换位置变成「换了一道题」）。
// e2e 从这份数据里 findIndex(o => o.correct) 取位置，跟着打散走，契约不变。
function hashSeed(id: string): number {
  let h = 2166136261
  for (let i = 0; i < id.length; i++) {
    h ^= id.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  return h >>> 0
}

function shuffleChoices(labels: [string, string, string], correctAt: number, seed: number): StepChoice[] {
  return shuffle(
    labels.map((label, i) => ({ label, correct: i === correctAt })),
    mulberry32(seed),
  )
}

/**
 * 构造一道题：askOptions / firstOptions 里各自有且仅有一个 correct。
 * 写题时把正确项放 index 0 即可；q() 会按 id 确定性打散，防止「闭眼选 A」。
 * e2e 从数据读正确项下标，不受打散影响。
 */
const q = (
  id: string,
  topic: ProblemTopic,
  segments: StemSegment[],
  askOptions: [string, string, string],
  askCorrect: number,
  firstOptions: [string, string, string],
  firstCorrect: number,
  steps: string[],
  answer: number,
  explain: string,
): WordProblem => {
  const seed = hashSeed(id)
  return {
    id,
    topic,
    text: segments.map((seg) => seg.t).join(''),
    segments,
    ask: {
      prompt: '这道题要我找什么？',
      options: shuffleChoices(askOptions, askCorrect, seed),
    },
    first: {
      prompt: '先算什么？',
      options: shuffleChoices(firstOptions, firstCorrect, seed ^ 0x9e3779b9),
    },
    steps,
    answer,
    explain,
  }
}

