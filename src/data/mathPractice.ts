// ---------- 带种子的伪随机（mulberry32，可复现）----------
function mulberry32(seed: number): () => number {
  let a = seed >>> 0
  return () => {
    a |= 0
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

function shuffle<T>(arr: T[], rnd: () => number): T[] {
  const a = arr.slice()
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

/** 抽一组题（给定 seed 可复现）。ids 非空时只取这些 id（重练错题）。 */
export function wordProblemRound(
  count = 5,
  seed: number = Date.now(),
  ids?: string[],
): WordProblem[] {
  const pool = ids && ids.length
    ? WORD_PROBLEMS.filter((p) => ids.includes(p.id))
    : shuffle(WORD_PROBLEMS, mulberry32(seed))
  return pool.slice(0, ids && ids.length ? pool.length : Math.min(count, pool.length))
}
