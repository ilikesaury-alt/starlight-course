// ============================================================
//  应用题专项练习 · 题目数据（北师大三年级上册）
//  ------------------------------------------------------------
//  针对陈老师反馈的「读题习惯差 / 不圈关键词」+ 用户实况：计算另有
//  《计算小能手》在练，这里**只做应用题**。线上原版「把所有文字都圈上
//  才算全对」不好用，已改为**引导式三步问**：
//    ① 这题求什么？    —— 读懂问题（选项 = 各种可能的目标）
//    ② 先算什么？      —— 理清步骤（选项 = 分步算式，含易错干扰项）
//    ③ 算出得数        —— 填最终答案
//  每一步都给即时反馈；做错的书进 localStorage（mathWrong.ts），
//  结算后可「重练做错的题」，不再单设「错因复盘」Tab。
//
//  答案、分步算式全部代码校验：单测钉死「分步末步结果 = answer」，
//  出题时不会算错。给定 seed 可复现，便于 e2e 用固定题面断言。
//
//  本项目是英语学习工作台，这里**不接入 SRS / store / ModuleId**，
//  错题单独存 localStorage（见 mathWrong.ts），不升 persist 版本号。
// ============================================================

export interface StepChoice {
  label: string
  correct: boolean
}

export interface WordProblem {
  id: string
  /** 完整题干（两步应用题，中文） */
  text: string
  /** 第一步：这题求什么？选项里恰有一个正确 */
  ask: { prompt: string; options: StepChoice[] }
  /** 第二步：先算什么？选项里恰有一个正确 */
  first: { prompt: string; options: StepChoice[] }
  /** 分步算式（用于第二步提示 + 解析展示） */
  steps: string[]
  answer: number
  explain: string
}

/**
 * 构造一道题：askOptions / firstOptions 里各自有且仅有一个 correct。
 * 选项顺序固定（不随机），这样 e2e 可以用 nth 定位，孩子每次看到一致的布局。
 */
const q = (
  id: string,
  text: string,
  askOptions: [string, string, string],
  askCorrect: number,
  firstOptions: [string, string, string],
  firstCorrect: number,
  steps: [string, string],
  answer: number,
  explain: string,
): WordProblem => ({
  id,
  text,
  ask: {
    prompt: '这题求什么？',
    options: askOptions.map((label, i) => ({ label, correct: i === askCorrect })),
  },
  first: {
    prompt: '先算什么？',
    options: firstOptions.map((label, i) => ({ label, correct: i === firstCorrect })),
  },
  steps,
  answer,
  explain,
})

